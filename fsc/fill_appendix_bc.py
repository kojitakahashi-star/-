def style_from(ws, src_coord, target):
    src = ws[src_coord]
    target.font = copy.copy(src.font)
    target.border = copy.copy(src.border)
    target.fill = copy.copy(src.fill)


def main():
    import os
    os.makedirs(OUT_DIR, exist_ok=True)

    # ---- 附則B ----
    wb = openpyxl.load_workbook(SRC_B)
    ws = wb.active
    for row, (proc, page) in B_MAP.items():
        c = ws.cell(row=row, column=3)
        d = ws.cell(row=row, column=4)
        style_from(ws, f'B{row}', c)
        style_from(ws, f'B{row}', d)
        c.value = proc
        d.value = page
        c.font = copy.copy(ws[f'B{row}'].font)
        c.alignment = Alignment(wrap_text=True, vertical='center', horizontal='left')
        d.alignment = Alignment(wrap_text=True, vertical='center', horizontal='center')
    ws.column_dimensions['C'].width = 78
    ws.column_dimensions['D'].width = 16
    for row in B_MAP:
        ws.row_dimensions[row].height = None
    wb.save(f'{OUT_DIR}/附則B  管理計画の要素_資料編ver.2反映.xlsx')

    # ---- 附則C ----
    wb = openpyxl.load_workbook(SRC_C)
    ws = wb.active
    for row, val in C_MAP.items():
        f = ws.cell(row=row, column=6)
        style_from(ws, f'A{row}', f)
        f.value = val
        f.alignment = Alignment(wrap_text=True, vertical='center', horizontal='left')
    ws.column_dimensions['F'].width = 82
    for row in C_MAP:
        ws.row_dimensions[row].height = None
    wb.save(f'{OUT_DIR}/附則C  モニタリング要求事項_資料編ver.2反映.xlsx')
    print('done', len(B_MAP), len(C_MAP))


if __name__ == '__main__':
    main()
